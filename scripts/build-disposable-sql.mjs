// Writes supabase/migrations/0006_disposable_emails.sql from supabase/disposable/domains.txt: the table of
// throwaway email domains and the "Before User Created" hook that refuses a sign-up from one.
// Usage: node scripts/build-disposable-sql.mjs   (then run the file in Supabase → SQL Editor)
import { readFileSync, writeFileSync } from 'node:fs'

const DOMAIN = /^[a-z0-9-]+(\.[a-z0-9-]+)+$/
const domains = [
  ...new Set(
    readFileSync(new URL('../supabase/disposable/domains.txt', import.meta.url), 'utf8')
      .split('\n')
      .map((l) => l.trim().toLowerCase())
      .filter((l) => l && !l.startsWith('#')),
  ),
].sort()
const bad = domains.filter((d) => !DOMAIN.test(d))
if (bad.length) throw new Error(`not a domain: ${bad.slice(0, 5).join(', ')}`)

const chunks = []
for (let i = 0; i < domains.length; i += 500) chunks.push(domains.slice(i, i + 500))
const inserts = chunks.map((c) => `insert into public.blocked_email_domains (domain) values\n${c.map((d) => `('${d}')`).join(',\n')}\non conflict do nothing;`).join('\n\n')

const sql = `-- ---------------------------------------------------------------------------
-- Throwaway email addresses may not open an account (security review 2026-10-22). Generated by
-- scripts/build-disposable-sql.mjs from supabase/disposable/domains.txt (${domains.length} domains, CC0): do not edit by hand.
--
-- 1. Run this whole file once in Supabase → SQL Editor. The last query lists the accounts that already use such an address.
-- 2. Supabase → Authentication → Auth Hooks → Add hook → "Before User Created" → Postgres → schema public,
--    function hook_before_user_created → Create. From then on a sign-up (email, magic link or Google) with a
--    domain in the table, or a subdomain of one, is refused; the app says why ("disposable_email").
-- One more domain later: insert into public.blocked_email_domains (domain) values ('example.com') on conflict do nothing;

create table if not exists public.blocked_email_domains (
  domain text primary key check (domain ~ '^[a-z0-9-]+(\\.[a-z0-9-]+)+$')
);
alter table public.blocked_email_domains enable row level security;
-- Only the sign-up check reads it (no policy for the app's keys).
drop policy if exists "auth reads blocked domains" on public.blocked_email_domains;
create policy "auth reads blocked domains" on public.blocked_email_domains for select to supabase_auth_admin using (true);
grant select on public.blocked_email_domains to supabase_auth_admin;

${inserts}

create or replace function public.hook_before_user_created(event jsonb)
returns jsonb
language plpgsql stable set search_path = '' as $$
declare
  host text := lower(split_part(coalesce(event -> 'user' ->> 'email', ''), '@', 2));
  parts text[] := string_to_array(host, '.');
begin
  if host = '' or parts is null then return '{}'::jsonb; end if;
  -- The domain itself or any parent of it (mail.throwaway.com is throwaway.com's).
  for i in 1 .. greatest(array_length(parts, 1) - 1, 1) loop
    if exists (select 1 from public.blocked_email_domains b where b.domain = array_to_string(parts[i:], '.')) then
      return jsonb_build_object('error', jsonb_build_object('http_code', 400,
        'message', 'disposable_email: Tek kullanımlık e-posta adresleriyle hesap açılamıyor.'));
    end if;
  end loop;
  return '{}'::jsonb;
end;
$$;

grant usage on schema public to supabase_auth_admin;
grant execute on function public.hook_before_user_created(jsonb) to supabase_auth_admin;
revoke execute on function public.hook_before_user_created(jsonb) from authenticated, anon, public;

-- The accounts already made with such an address (to look at; delete them in Authentication → Users if you wish).
select u.id, u.email, u.created_at, u.last_sign_in_at
from auth.users u
where exists (
  select 1 from public.blocked_email_domains b
  where lower(split_part(u.email, '@', 2)) = b.domain or lower(split_part(u.email, '@', 2)) like '%.' || b.domain
)
order by u.created_at desc;
`
writeFileSync(new URL('../supabase/migrations/0006_disposable_emails.sql', import.meta.url), sql)
console.log(`0006_disposable_emails.sql: ${domains.length} domains`)
