/**
 * Generates a practice round of collocation / preposition questions,
 * prioritizing previous misses and unseen items.
 */
export function collocationDrillRound(
  language: TargetLanguage,
  log: GrammarLog = {},
  count = 10,
  rng: Rng = Math.random
): CollocationDrillItem[] {
  const pool = COLLOCATION_DRILLS.filter((c) => c.language === language)
  if (!pool.length) return []

  const scored = pool.map((item) => {
    const entry = log[item.id]
    let weight = 1
    if (!entry) {
      weight = 4 // unseen
    } else if (entry.wrong > entry.ok) {
      weight = 6 // struggled
    } else if (entry.wrong > 0) {
      weight = 3 // previously made mistakes
    } else {
      weight = 1 // mastered
    }
    return { item, sortKey: rng() * weight }
  })

  scored.sort((a, b) => b.sortKey - a.sortKey)
  return scored.slice(0, count).map((s) => s.item)
}
